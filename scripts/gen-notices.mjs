// Regenerates THIRD_PARTY_NOTICES.md: the components a vihpluh binary contains or loads, with
// their licences. Rust crates come from `cargo metadata` (every platform's dependencies),
// npm packages from `pnpm licenses` (production dependencies only — what ends up in the
// bundle). Run with `pnpm gen:notices` after changing dependencies.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const run = (command) =>
  execSync(command, { cwd: root, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });

/** `MIT/Apache-2.0` and `Apache-2.0 / MIT` are old spellings of `MIT OR Apache-2.0`. */
function normalise(licence) {
  const text = (licence ?? "").trim().replace(/\s*\/\s*/g, " OR ");
  if (!text.includes(" AND ") && !text.includes("(")) {
    return text.split(" OR ").sort().join(" OR ");
  }
  return text;
}

function crates() {
  const metadata = JSON.parse(
    run("cargo metadata --manifest-path src-tauri/Cargo.toml --format-version 1"),
  );
  return metadata.packages
    .filter((p) => p.source !== null)
    .map((p) => ({
      name: p.name,
      version: p.version,
      licence: normalise(p.license) || "see the crate",
      url: p.repository ?? p.homepage ?? `https://crates.io/crates/${p.name}`,
    }));
}

function npmPackages() {
  const byLicence = JSON.parse(run("pnpm licenses list --prod --json"));
  const out = [];
  for (const [licence, packages] of Object.entries(byLicence)) {
    for (const p of packages) {
      for (const version of p.versions) {
        out.push({
          name: p.name,
          version,
          licence: normalise(licence),
          url: p.homepage ?? `https://www.npmjs.com/package/${p.name}`,
        });
      }
    }
  }
  return out;
}

function table(items) {
  const groups = new Map();
  for (const item of items) {
    if (!groups.has(item.licence)) groups.set(item.licence, []);
    groups.get(item.licence).push(item);
  }
  const lines = [];
  const licences = [...groups.keys()].sort(
    (a, b) => groups.get(b).length - groups.get(a).length || a.localeCompare(b),
  );
  for (const licence of licences) {
    const members = groups
      .get(licence)
      .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
    lines.push(`### ${licence} (${members.length})`, "");
    lines.push(members.map((m) => `[${m.name}](${m.url}) ${m.version}`).join(" · "), "");
  }
  return lines.join("\n");
}

