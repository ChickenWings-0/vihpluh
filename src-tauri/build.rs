use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap_or_default());
    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let target_env = env::var("CARGO_CFG_TARGET_ENV").unwrap_or_default();

    match target_os.as_str() {
        "windows" => link_libmpv_windows(&manifest_dir, &target_env),
        _ => link_libmpv_pkg_config(),
    }

    tauri_build::build();
}

/// Windows: link the pinned libmpv fetched by `pnpm fetch:libmpv` and place the DLL beside the
/// built executable so `tauri dev` runs without PATH changes (ARCHITECTURE §12.1).
fn link_libmpv_windows(manifest_dir: &Path, target_env: &str) {
    let lib_dir = manifest_dir.join("lib").join("windows-x64");
    let dll = lib_dir.join("libmpv-2.dll");
    println!("cargo:rerun-if-changed={}", lib_dir.join(".stamp").display());

    if !dll.exists() {
        fail("libmpv-2.dll is missing. Run `pnpm fetch:libmpv` first.");
    }
    // MSVC links mpv.lib (generated by the fetch script); the GNU toolchain links the MinGW
    // import library that ships in the archive.
    let import_lib = if target_env == "msvc" { "mpv.lib" } else { "libmpv.dll.a" };
    if !lib_dir.join(import_lib).exists() {
        fail(&format!(
            "{import_lib} is missing from {}. Run `pnpm fetch:libmpv -- -Force` \
             (the MSVC toolchain needs llvm-dlltool or lib.exe on this machine).",
            lib_dir.display()
        ));
    }
    println!("cargo:rustc-link-search=native={}", lib_dir.display());

    // OUT_DIR = <target>/<profile>/build/<pkg>-<hash>/out
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap_or_default());
    if let Some(profile_dir) = out_dir.ancestors().nth(3) {
        let dest = profile_dir.join("libmpv-2.dll");
        if !same_size(&dll, &dest) {
            if let Err(err) = fs::copy(&dll, &dest) {
                println!("cargo:warning=could not copy libmpv-2.dll to {}: {err}", dest.display());
            }
        }
    }
}

/// Linux: the system libmpv (`mpv-devel`) is located through pkg-config.
fn link_libmpv_pkg_config() {
    match Command::new("pkg-config").args(["--libs-only-L", "mpv"]).output() {
        Ok(out) if out.status.success() => {
            for token in String::from_utf8_lossy(&out.stdout).split_whitespace() {
                if let Some(dir) = token.strip_prefix("-L") {
                    println!("cargo:rustc-link-search=native={dir}");
                }
            }
        }
        _ => fail("pkg-config could not find mpv. Install it with `sudo dnf install mpv-devel`."),
    }
}

fn same_size(a: &Path, b: &Path) -> bool {
    match (fs::metadata(a), fs::metadata(b)) {
        (Ok(a), Ok(b)) => a.len() == b.len(),
        _ => false,
    }
}

fn fail(message: &str) -> ! {
    eprintln!("error: {message}");
    std::process::exit(1);
}
